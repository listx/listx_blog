#!/usr/bin/env python3

from math import isqrt
from lib import draw_circle_points, mirror_points_4, mirror_points_8


def draw_circle_naive(r):
    """ Draw a circle by collecting all quarter-circle that lie on a circle at
    the origin with radius 'r'. This has a bug because some Y values get
    skipped. Can you see why?
    """
    points = []
    for x in range(r + 1):
        y = isqrt((r * r) - (x * x))
        points.extend(mirror_points_4(x, y))
    draw_circle_points(points, r)


def draw_circle_slow(r):
    """ Better than draw_circle_naive, but wastes CPU cycles because the 8-way
    symmetry overcorrects and we draw some pixels more than once.
    """
    points = []
    for x in range(r + 1):
        y = isqrt((r * r) - (x * x))
        points.extend(mirror_points_8(x, y))
    draw_circle_points(points, r)


def draw_circle_inefficient(r):
    """ Slightly faster than draw_circle_slow, because of the break condition
    at the middle of the arc. However this is inefficient due to the square
    root calculation.
    """
    points = []
    for x in range(r + 1):
        y = isqrt((r * r) - (x * x))
        # When we cross the middle of the arc, stop, because we're already
        # invoking 8-way symmetry.
        if x > y:
            break
        points.extend(mirror_points_8(x, y))
    draw_circle_points(points, r)


